#!/bin/sh
# UserPromptSubmit 훅: 사용자 메시지가 요구사항/구현 상태 표·체크리스트·리스트업을 요청하면, 보고 전 각 항목을 실제로 확인하라는 중립적 리마인더를 컨텍스트에 추가
# 응답이 실제로 각 항목을 Read/Grep으로 확인했는지는 사후에도 검증 불가 - 놓치는 빈도를 줄이는 넛지일 뿐, 사후 확인은 사용자가 직접 수행

input=$(cat)
prompt=$(printf '%s' "$input" | sh "$(dirname "$0")/user-prompt-text.sh")

case "$prompt" in
  *표로*|*리스트업*|*체크리스트*|*반영됐는지*|*반영됐나*|*구현됐는지*|*구현상태*|*"구현 상태"*)
    echo "상태표/체크리스트 요청 감지: '미확인'으로 채우지 말고, 각 행의 근거 파일을 Read/Grep으로 실제 확인한 뒤에만 보고할 것."
    ;;
esac

exit 0
